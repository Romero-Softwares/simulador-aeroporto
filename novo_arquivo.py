# Bem-vindo ao Merotec IA IDE

# Como comecar
# 1. Abra uma pasta de projeto em Arquivo > Abrir projeto.
# 2. Selecione um arquivo no painel PROJETOS para edita-lo.
# 3. Crie arquivos pelo botao + ou use Arquivo > Novo arquivo.
# 4. Execute o arquivo Python aberto pelo botao ▶ ou menu Executar.

# Teste visual de projetos
# Flutter: no terminal, execute `flutter pub get` e depois `flutter run -d chrome`.
#          Para abrir como aplicativo Windows, use `flutter run -d windows`.
# Flet: execute `flet run main.py --web` para abrir no navegador.
#       Sem `--web`, `flet run main.py` abre a janela do aplicativo.
# Python: abra o arquivo principal e pressione F5; a saida aparece no terminal.
# HTML/CSS/JS: execute `python -m http.server 8000 --bind 127.0.0.1`
#               e abra http://127.0.0.1:8000 no navegador.
# Flask API: execute `flask --app app run --debug` e abra http://127.0.0.1:5000.
#            Troque `app` pelo arquivo/modulo que contem a aplicacao, se necessario.
# FastAPI: execute `uvicorn main:app --reload` e abra http://127.0.0.1:8000/docs.
#          Troque `main:app` pelo modulo e objeto da sua API, se necessario.

# C++: abra um arquivo .cpp e pressione F5; a IDE usa g++ para compilar e executar.
# C#: abra Program.cs e pressione F5; a IDE executa o projeto com `dotnet run`.

# Terminal
# Digite comandos na caixa abaixo do terminal e pressione Enter.
# O comando e executado na pasta do projeto aberto. Para parar um servidor, use Ctrl+C.
# Use Interromper para encerrar um processo em execucao.

# Atalhos
# Ctrl+S  Salvar arquivo
# Ctrl+`  Focar o terminal
# Ctrl+C  Interromper o processo do terminal

